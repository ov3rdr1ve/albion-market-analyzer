// Base crafting fame multiplier per item tier (× non-artifact material count).
const CRAFT_BASE_FAME_MULT = { 1: 0, 2: 1.5, 3: 7.5, 4: 22.5, 5: 90, 6: 270, 7: 645, 8: 1395 };

// Crafting journal maxfame (base fame to fill), straight from items.xml
// `<journalitem maxfame="…">` for T{n}_JOURNAL_{WARRIOR|HUNTER|MAGE|TOOLMAKER}.
// T7/T8 are NOT the round doubling this table used to assume (28800/57600) —
// the game files stop doubling there. js/data-craft-journal-fame.js carries the
// generated copy and wins; this stays as the standalone fallback.
const CRAFT_JOURNAL_FAME = { 2: 900, 3: 1800, 4: 3600, 5: 7200, 6: 14400, 7: 28380, 8: 58590 };

const CRAFT_JOURNAL_SLUGS = ["WARRIOR", "HUNTER", "MAGE", "TOOLMAKER"];
const CRAFT_JOURNAL_TIERS = [2, 3, 4, 5, 6, 7, 8];

// ── local id helpers (kept self-contained so this file + its test stand alone) ──
function _cpTier(id) {
  const m = id && id.match(/^T(\d+)/);
  return m ? parseInt(m[1], 10) : 4;
}
function _cpEnchant(id) {
  const m = id && id.match(/@(\d+)$/);
  return m ? parseInt(m[1], 10) : 0;
}

// The generated per-item map. A plain <script> supplies it in the browser and a
// require picks it up under Node; resolved lazily and defensively because some
// tests evaluate this file through `vm` under a synthetic filename, where a
// relative require cannot resolve.
let _cpJournalFameCache;
function _cpJournalFame() {
  if (_cpJournalFameCache !== undefined) return _cpJournalFameCache;
  if (typeof getCraftJournalForItem === "function" &&
      typeof CRAFT_JOURNAL_MAXFAME !== "undefined") {
    _cpJournalFameCache = { getCraftJournalForItem, CRAFT_JOURNAL_MAXFAME };
  } else if (typeof require === "function") {
    try {
      _cpJournalFameCache = require("./data-craft-journal-fame.js");
    } catch (e) {
      _cpJournalFameCache = null;
    }
  } else {
    _cpJournalFameCache = null;
  }
  return _cpJournalFameCache;
}

// Which crafting journal (slug) does crafting `item` fill? Answered per item id
// from items.xml's own <craftitemfame><validitem> lists — NOT from craftType,
// which cannot tell a plain cape (fills Toolmaker) from an artifact cape (fills
// nothing). Returns null for crafts in no list: combines, consumables, mounts,
// T1 gear, and anything the game simply awards no journal fame for.
function getCraftJournalSlug(item) {
  if (!item || !item.id) return null;
  const api = _cpJournalFame();
  if (!api) return null;
  const hit = api.getCraftJournalForItem(item.id);
  return hit ? hit.slug : null;
}

// How many crafts it takes to fill one journal. One craft never fills a journal,
// so the journal's silver is worth `1 / craftsToFill` of itself per craft — the
// per-fame maths the callers use is this same split written the other way round.
// Left fractional on purpose: a part-filled journal still carries its fame.
function getCraftsToFillJournal(famePerCraft, maxfame) {
  if (!(famePerCraft > 0) || !(maxfame > 0)) return 0;
  return maxfame / famePerCraft;
}

// Journal fame awarded for ONE craft of `item` consuming `nonArtifactMats`
// non-artifact materials:
//
//   fame = nonArtifactMats × CRAFT_BASE_FAME_MULT[tier] × 2^enchant
//
// Enchant DOUBLES the fame per level off the item's OWN tier. It does not raise
// the effective tier, which is what this used to do: the multiplier table is not
// a doubling (90→270 is ×3, 645→1395 is ×2.16) and it stops at T8, so that rule
// was ~29% high on a T6.2 and dropped the enchant bonus entirely on every T8.n.
//
// Measured in game (forum thread 167786): an Adept's Bloodletter 4.2 — 16 rare
// worked leather + 8 rare steel bar + 1 artifact — awarded exactly
// 24 × 22.5 × 2^2 = 2,160 journal fame. Note the artifact is simply absent from
// the count; artifacts have not affected fame gain since crafting masteries were
// split per artifact item, so there is no (1+itemTypeFactor) term to add.
function getCraftingFamePerCraft(item, nonArtifactMats, enchantLevel) {
  if (!nonArtifactMats || nonArtifactMats <= 0) return 0;
  const tier = _cpTier(item && item.id);
  const ench = enchantLevel != null ? enchantLevel : _cpEnchant(item && item.id);
  return nonArtifactMats * (CRAFT_BASE_FAME_MULT[tier] || 0) * Math.pow(2, ench);
}

// The crafting journal a tier-`craftTier` craft can fill — its OWN tier and
// nothing else. The ±2 window in data-journals.js belongs to the GATHERING
// journals, whose <gatherfame> blocks really do list three tiers of resource; a
// crafting journal's <craftitemfame> lists only items of its own tier, so a T8
// craft cannot fill a T6 journal. Returns the real empty/full market ids +
// maxfame. Empty for a null slug or a tier with no journal (T1).
function getCraftPlannerJournalCandidates(slug, craftTier) {
  if (!slug || !CRAFT_JOURNAL_TIERS.includes(craftTier)) return [];
  const api = _cpJournalFame();
  const maxfame =
    (api && api.CRAFT_JOURNAL_MAXFAME[craftTier]) ||
    CRAFT_JOURNAL_FAME[craftTier] ||
    0;
  if (!maxfame) return [];
  return [{
    slug,
    tier: craftTier,
    emptyId: `T${craftTier}_JOURNAL_${slug}_EMPTY`,
    fullId: `T${craftTier}_JOURNAL_${slug}_FULL`,
    maxfame,
  }];
}

// Every crafting-journal market id the scan needs (4 slugs × 7 tiers × {E,F}).
function getCraftPlannerJournalIds() {
  const ids = [];
  CRAFT_JOURNAL_SLUGS.forEach((slug) => {
    CRAFT_JOURNAL_TIERS.forEach((tier) => {
      ids.push(`T${tier}_JOURNAL_${slug}_EMPTY`);
      ids.push(`T${tier}_JOURNAL_${slug}_FULL`);
    });
  });
  return ids;
}

// Every market id the Crafting Planner scan needs: the Crafting table's BASE
// (non-enchant) item + recipe-mat ids PLUS every refining-chain intermediate raw
// for those mats (so refine-vs-buy can be priced at each tier) PLUS the crafting
// journals. The base scan deliberately drops the catalogue's `@n` enchant
// variants — fetching them all up front bloats the id set ~8971→~2522
// (60→~17 chunks, ~3.6min→~1min), so the journals (the last chunk) populate
// before a user gives up or hits the rate limit. The enchant (.1–.4) rows ARE
// rendered (via the enchant picker / row expand); their prices are fetched
// lazily on demand instead — see ensurePlannerVariantPrices in
// render-craft-planner.js. Browser-runtime only (depends on getCraftingItemIds /
// getRefiningChainIds globals); falls back gracefully if either is absent.
function getCraftPlannerItemIds() {
  const ids = new Set();
  const base = (typeof getCraftingItemIds === "function") ? getCraftingItemIds() : [];
  base.forEach((id) => {
    if (String(id).includes("@")) return; // enchant variant — not rendered by the planner
    ids.add(id);
    if (typeof getRefiningChainIds === "function") {
      // CP_CHAIN_OPTS: the planner's chains price a transmuted raw, so the grid
      // nodes the DP reads have to be in the batch or it only ever sees zeros.
      // For a plain (.0) row that is just T4-T8 of one family, nearly all of
      // which the ladder already pulls in.
      getRefiningChainIds(id, undefined, { transmuteRaw: true }).forEach((x) => ids.add(x));
    }
  });
  getCraftPlannerJournalIds().forEach((id) => ids.add(id));
  // Enchanting materials T4-T8 × RUNE/SOUL/RELIC: the planner prices the
  // buy-the-@(n-1)-and-enchant-up acquisition route on its .1-.3 rows
  // (js/craft-planner-enchant-route.js), so the runes must be in the batch.
  for (let t = 4; t <= 8; t++) {
    ids.add(`T${t}_RUNE`);
    ids.add(`T${t}_SOUL`);
    ids.add(`T${t}_RELIC`);
  }
  // Crystallized tokens and the expiring Crystal twins: the planner prices them
  // against the artifact they can replace, same as the Crafting table
  // (js/gear-token-substitute.js, js/utils.js).
  if (typeof getArtifactTokenIds === "function") getArtifactTokenIds(ids);
  if (typeof getArtifactDecayIds === "function") getArtifactDecayIds(ids);
  // Refined mix a crafting laborer hands back for a worked journal — priced by
  // the Laborer Journal column (js/laborer-journal-value.js).
  if (typeof getLaborerJournalPayoutIds === "function") {
    getLaborerJournalPayoutIds().forEach((id) => ids.add(id));
  }
  return Array.from(ids);
}

