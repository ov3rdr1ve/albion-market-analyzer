// Crafting Planner — data + lookups for the vertical "refine the ladder, craft
// the top item" view. This file is the catalogue/tunables only; the end-to-end
// economics live in js/craft-planner-pricing.js and the render in
// js/render-craft-planner.js.
//
// Two things the planner needs beyond the existing Crafting table:
//
//  1. Which CRAFTING JOURNAL a craft fills (so we can value journal-fill silver
//     per craft, the analogue of the Gathering table's journal column). Answered
//     PER ITEM from items.xml — every <journalitem> lists the exact ids that
//     fill it — via js/data-craft-journal-fame.js. The four professions still
//     read the way you'd expect (Warrior's Forge → WARRIOR, Hunter's Lodge →
//     HUNTER, Mage's Tower → MAGE, Toolmaker → TOOLMAKER : tools, furniture,
//     capes, bags, gatherer gear), but the list is the authority: the COMBINE
//     crafts that share those craft types — artifact/faction capes, Royal
//     armour, Crystal weapons, Shapeshifter staves — fill NO journal, and a
//     craftType rule silently credited them with one.
//     Crafting journal market ids are real game ids (T8_JOURNAL_WARRIOR_FULL …)
//     so AODP prices resolve — see [[project_app_catalog_architecture]].
//
//  2. How much JOURNAL FAME a single craft awards (so crafts-to-fill = journal
//     maxfame ÷ fame-per-craft):
//
//       fame = nonArtifactMats × mult[tier] × 2^enchant
//       mult = T1:0 T2:1.5 T3:7.5 T4:22.5 T5:90 T6:270 T7:645 T8:1395
//
//     Enchant DOUBLES the fame per level off the item's own tier. It does NOT
//     raise the effective tier — that was the old rule here, and the multiplier
//     table is not a doubling (90→270 is ×3) and stops at T8, so it read high on
//     mid-tier enchants and lost the bonus entirely on T8.n.
//
//     Artifacts do not affect fame gain (they simply do not count as materials)
//     and Royal items award none, so there is no (1+itemTypeFactor) term. The
//     wiki's Fame page still carries that older formula; the version here is the
//     one that reproduces measured in-game numbers — an Adept's Bloodletter 4.2
//     with 24 non-artifact mats awards 24 × 22.5 × 2^2 = 2,160 (forum 167786).

