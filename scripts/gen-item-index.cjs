/**
 * Generate js/item-index.js from ao-bin-dumps `formatted/items.txt`.
 *
 * The market-history response the monitor captures names its item only by a
 * NUMBER — the AlbionId the request carried (js/market-history-volume.js).
 * That number is the line index in ao-bin-dumps items.txt, which is the same
 * mapping AODP's ingest uses to name uploaded histories. The local items.xml
 * cannot stand in for it: its element order does not match the dump's index
 * (verified — they diverge from entry 2 onward).
 *
 * Only ids the app can actually price are shipped: an index the catalogs never
 * mention would just be dead weight in a map that is otherwise ~12k entries.
 * "Can price" is deliberately loose here — every id mentioned anywhere in js/
 * plus every tiered or UNIQUE_ id in items.xml — a captured history for an
 * id the app does not track simply produces no patch.
 *
 * Run: node scripts/gen-item-index.cjs [path/to/items.txt]
 *   With no argument the dump is fetched from GitHub.
 */

const fs = require("fs");
const path = require("path");
const https = require("https");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "js", "item-index.js");
const DUMP_URL = "https://raw.githubusercontent.com/ao-data/ao-bin-dumps/master/formatted/items.txt";

function fetchText(url) {
  return new Promise((resolve, reject) => {
    https.get(url, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        resolve(fetchText(res.headers.location));
        return;
      }
      if (res.statusCode !== 200) {
        reject(new Error(`${url} → HTTP ${res.statusCode}`));
        return;
      }
      let body = "";
      res.setEncoding("utf8");
      res.on("data", (chunk) => { body += chunk; });
      res.on("end", () => resolve(body));
    }).on("error", reject);
  });
}

/** "  2832: T4_BAG   : Adept's Bag" → [2832, "T4_BAG"] */
function parseDump(text) {
  const out = [];
  text.split(/\r?\n/).forEach((line) => {
    const m = line.match(/^\s*(\d+):\s*(\S+)/);
    if (m) out.push([Number(m[1]), m[2]]);
  });
  return out;
}

/** Every id the app could plausibly ask about. */
function knownIds() {
  const ids = new Set();
  const add = (id) => { if (id) ids.add(id); };

  const jsDir = path.join(ROOT, "js");
  fs.readdirSync(jsDir)
    .filter((f) => f.endsWith(".js") || f.endsWith(".json"))
    .forEach((f) => {
      const text = fs.readFileSync(path.join(jsDir, f), "utf8");
      const re = /\b(?:T\d_[A-Z0-9_]+(?:@\d)?|UNIQUE_[A-Z0-9_]+(?:@\d)?|QUESTITEM_[A-Z0-9_]+|TREASURE_[A-Z0-9_]+)\b/g;
      let m;
      while ((m = re.exec(text)) !== null) add(m[0]);
    });

  const xmlPath = path.join(ROOT, "data", "dumps", "items.xml");
  if (fs.existsSync(xmlPath)) {
    const xml = fs.readFileSync(xmlPath, "utf8");
    const re = /uniquename="([^"]+)"/g;
    let m;
    while ((m = re.exec(xml)) !== null) add(m[1]);
  }
  return ids;
}

async function main() {
  const arg = process.argv[2];
  const text = arg ? fs.readFileSync(arg, "utf8") : await fetchText(DUMP_URL);
  const entries = parseDump(text);
  if (entries.length < 1000) throw new Error(`items.txt looks wrong: ${entries.length} entries`);

  const known = knownIds();
  const kept = {};
  let enchantsKept = 0;
  entries.forEach(([index, id]) => {
    // Enchanted variants are their own index in the dump; keep one whenever the
    // base id is known, since @n prices are a first-class part of the app.
    const base = id.replace(/@\d$/, "");
    if (!known.has(id) && !known.has(base)) return;
    kept[index] = id;
    if (id !== base) enchantsKept++;
  });

  const body = `// AUTO-GENERATED by scripts/gen-item-index.cjs from ao-bin-dumps formatted/items.txt.
// Do not edit by hand — re-run the script after an items.xml / dump refresh.
//
// AlbionId (the numeric item index the market-history request carries) → game
// id. Only ids the app's catalogs mention are shipped; anything else could not
// be priced anyway. See js/market-history-volume.js.
const ALBION_ITEM_INDEX = ${JSON.stringify(kept)};

/** Game id for a captured AlbionId, or null when the index is unknown. */
function albionItemIdFromIndex(index) {
  const n = Number(index);
  if (!Number.isFinite(n)) return null;
  return ALBION_ITEM_INDEX[n] || null;
}

if (typeof module !== "undefined" && module.exports) {
  module.exports = { ALBION_ITEM_INDEX, albionItemIdFromIndex };
}
`;
  fs.writeFileSync(OUT, body);
  console.log(`items.txt entries: ${entries.length}`);
  console.log(`kept: ${Object.keys(kept).length} (${enchantsKept} enchanted variants)`);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${(body.length / 1024).toFixed(0)} KB)`);
}

main().catch((e) => { console.error(e.message); process.exit(1); });
