#!/usr/bin/env node
/**
 * Generate js/item-names-es.js — the Spanish (ES-ES) display-name lookup.
 *
 * Source of truth: ao-bin-dumps formatted/items.json (repo-local `data/dumps/items.json`),
 * the same dump the EN names come from. Each entry carries LocalizedNames with
 * an "ES-ES" key covering EVERY real game id (equipment, resources, mounts,
 * consumables, tokens…). We emit `UniqueName -> ES-ES` for every entry that has
 * a Spanish name.
 *
 * getItemDisplayName() (js/utils.js) consults ITEM_NAMES_ES first when the UI
 * language is "es"; anything absent here falls back to the English chain, so a
 * missing/stale dump entry never shows a raw id.
 *
 * Re-run after an items.json refresh:  node scripts/gen-item-names-es.cjs
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(ROOT, "data", "dumps", "items.json");
const OUT = path.join(ROOT, "js", "item-names-es.js");

const raw = JSON.parse(fs.readFileSync(SRC, "utf8"));
const arr = Array.isArray(raw) ? raw : raw.items || Object.values(raw);

const map = {};
let skipped = 0;
for (const entry of arr) {
  if (!entry || !entry.UniqueName) continue;
  const es = entry.LocalizedNames && entry.LocalizedNames["ES-ES"];
  if (!es || typeof es !== "string") {
    skipped++;
    continue;
  }
  map[entry.UniqueName] = es;
}

const header =
  "// AUTO-GENERATED by scripts/gen-item-names-es.cjs from items.json — do not edit by hand.\n" +
  "// Spanish (ES-ES) display names keyed by raw game id. getItemDisplayName()\n" +
  "// (js/utils.js) reads this first when the UI language is \"es\"; anything absent\n" +
  "// falls back to the English name chain. Re-run after an items.json refresh.\n";

const body = "const ITEM_NAMES_ES = " + JSON.stringify(map) + ";\n";
const footer =
  "if (typeof module !== \"undefined\" && module.exports) module.exports = { ITEM_NAMES_ES };\n";

fs.writeFileSync(OUT, header + body + footer, "utf8");
console.log(
  `Wrote ${OUT}: ${Object.keys(map).length} ES names (${skipped} entries had no ES-ES).`,
);
