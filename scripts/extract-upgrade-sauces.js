// One-off extractor: scans items.xml for every consumable's enchanted upgrade
// requirements (fishsauce / alchemy_extract counts per item per enchant level)
// and prints a JS-literal map. Pure file IO + regex, no shell exec.
//
// Usage: node scripts/extract-upgrade-sauces.js

const fs = require("fs");
const path = require("path");

const xml = fs.readFileSync(path.join(__dirname, "..", "data", "dumps", "items.xml"), "utf8");
const out = {};

const itemRe = /<consumableitem\s+uniquename="([^"]+)"([^>]*)>([\s\S]*?)<\/consumableitem>/g;
let m;
while ((m = itemRe.exec(xml)) !== null) {
  const id = m[1];
  const openAttrs = m[2];
  const body = m[3];
  // Cooked foods + potions. The dump has renamed both buckets over time —
  // foods went "cooked" → "food", classic potions "potion" → "potions" — so
  // accept every spelling and the script keeps working against either dump.
  if (!/shopsubcategory1="(cooked|food|potions?)"/.test(openAttrs)) continue;
  const enchRe = /<enchantment\s+enchantmentlevel="(\d)"[\s\S]*?<\/enchantment>/g;
  let e;
  const upgrades = [];
  while ((e = enchRe.exec(body)) !== null) {
    const level = parseInt(e[1], 10);
    const up = e[0].match(/<upgraderesource\s+uniquename="([^"]+)"\s+count="(\d+)"/);
    if (!up) continue;
    upgrades.push({ level, sauceMatId: up[1], count: parseInt(up[2], 10) });
  }
  if (upgrades.length) out[id] = upgrades;
}

const ids = Object.keys(out).sort();
console.log("// AUTO-GENERATED by scripts/extract-upgrade-sauces.js from items.xml — do not edit by hand.");
console.log("// Enchant upgrade sauce per (consumable, enchant level), from <upgraderequirements>.");
console.log("// Re-run: node scripts/extract-upgrade-sauces.js > js/data-enchant-sauces.js");
console.log("//");
console.log("// Foods upgrade with T1_FISHSAUCE_LEVEL{N} (levels 1/2/3). Every potion — classic");
console.log("// (Healing, Energy, Resistance, Gigantify, Invisibility, Sticky, Resurrection) and");
console.log("// rare/alchemy (Calming, Cleansing, Acid, Berserk, Gathering, Hellfire, Tornado) —");
console.log("// upgrades with T1_ALCHEMY_EXTRACT_LEVEL{N} (1/2/3). The old T{tier}_ESSENCE_POTION");
console.log("// upgrade is gone from the game files.");
console.log("//");
console.log("// Sauces are non-tradeable (the Albion API returns no price); kept in the recipe so the");
console.log("// breakdown column can render an editable price cell for the user's opportunity cost.");
console.log("const ENCHANT_UPGRADE_SAUCE = {");
for (const id of ids) {
  const list = out[id].map(u => `{ level: ${u.level}, sauceMatId: "${u.sauceMatId}", count: ${u.count} }`).join(", ");
  console.log(`  ${id}: [${list}],`);
}
console.log("};");
console.log(`// ${ids.length} entries`);
