/**
 * Extract focus costs from items.xml and output to js/focus-costs.json
 *
 * Parses all item elements with craftingfocus > 0 and maps:
 *   - Base items: uniquename -> first craftingfocus value
 *   - Enchanted resources: uniquename with _LEVEL{N} -> mapped to @{N} suffix
 *   - Consumable enchantments: nested <enchantment> elements with their own craftingfocus
 *
 * Usage: node scripts/extract-focus-costs.js
 */
const fs = require("fs");
const path = require("path");

const xmlPath = path.join(__dirname, "..", "data", "dumps", "items.xml");

const xml = fs.readFileSync(xmlPath, "utf-8");

const focusCosts = {};

// Match any item element with a uniquename attribute
// Pattern: <(weaponitem|equipmentitem|simpleitem|consumableitem|furnitureitem|...) uniquename="XXX" ...>
//   followed by <craftingrequirements ... craftingfocus="N" ...>
// We need to track the current parent item's uniquename and collect craftingfocus from its children.

const lines = xml.split("\n");
let currentItemName = null;
let currentItemHasFocus = false;
let inEnchantment = false;
let enchantmentLevel = null;

for (let i = 0; i < lines.length; i++) {
  const line = lines[i];

  // Detect item opening tags (any element with uniquename attribute at top level)
  const itemMatch = line.match(
    /<(?:weapon|weaponitem|equipmentitem|simpleitem|consumableitem|furnitureitem|farmableitem|mount|mountitem|journalitem|crystalleagueitem|hideoutitem|labourercontract|trackingitem|killtrophy|transformationweapon)\s[^>]*uniquename="([^"]+)"/
  );
  if (itemMatch) {
    currentItemName = itemMatch[1];
    currentItemHasFocus = false;
    inEnchantment = false;
    enchantmentLevel = null;
  }

  // Detect enchantment blocks inside consumables
  const enchMatch = line.match(/<enchantment\s[^>]*enchantmentlevel="(\d+)"/);
  if (enchMatch) {
    inEnchantment = true;
    enchantmentLevel = parseInt(enchMatch[1]);
  }

  // Detect closing enchantment
  if (line.includes("</enchantment>") || (inEnchantment && line.includes("</enchantments>"))) {
    inEnchantment = false;
    enchantmentLevel = null;
  }

  // Extract craftingfocus from craftingrequirements
  const focusMatch = line.match(/craftingfocus="(\d+)"/);
  if (focusMatch && currentItemName) {
    const focusValue = parseInt(focusMatch[1]);
    if (focusValue > 0) {
      if (inEnchantment && enchantmentLevel) {
        // Enchanted consumable variant — use @N suffix like the app does
        const enchKey = currentItemName + "@" + enchantmentLevel;
        if (!focusCosts[enchKey]) {
          focusCosts[enchKey] = focusValue;
        }
      } else if (!currentItemHasFocus) {
        // First craftingrequirements for base item (skip duplicates like faction recipes)
        // Map _LEVEL{N} suffix to @{N} to match app convention
        let key = currentItemName.replace(/_LEVEL(\d+)$/, "@$1");
        focusCosts[key] = focusValue;
        currentItemHasFocus = true;
      }
    }
  }

  // Detect item closing tags
  if (
    line.match(
      /<\/(?:weapon|weaponitem|equipmentitem|simpleitem|consumableitem|furnitureitem|farmableitem|mount|mountitem|journalitem|crystalleagueitem|hideoutitem|labourercontract|trackingitem|killtrophy|transformationweapon)>/
    )
  ) {
    currentItemName = null;
    currentItemHasFocus = false;
    inEnchantment = false;
    enchantmentLevel = null;
  }
}

// Refined enchanted resources: the market/AODP id format (and js/data.js's
// display-name keys) is T{n}_{RES}_LEVEL{k}@{k}, NOT T{n}_{RES}@{k}. Convert so
// focus keys match the ids used for pricing. This folds in the old one-off
// update_focus.js so a single `node scripts/extract-focus-costs.js` keeps the
// runtime file in sync with items.xml.
const REFINED = /^(T[4-8]_(?:CLOTH|LEATHER|METALBAR|PLANKS|STONEBLOCK|ROCK|ORE|WOOD|HIDE|FIBER))@([1-4])$/;
const converted = {};
for (const [k, v] of Object.entries(focusCosts)) {
  const m = k.match(REFINED);
  converted[m ? `${m[1]}_LEVEL${m[2]}@${m[2]}` : k] = v;
}

const sorted = Object.fromEntries(
  Object.entries(converted).sort(([a], [b]) => a.localeCompare(b))
);

// Two generated outputs, both from items.xml (single source of truth):
//   js/focus-costs.js   — the FOCUS_COSTS global the browser app loads
//   js/focus-costs.json — same data, consumed by tests
const jsonPath = path.join(__dirname, "..", "js", "focus-costs.json");
const jsPath = path.join(__dirname, "..", "js", "focus-costs.js");
fs.writeFileSync(jsonPath, JSON.stringify(sorted, null, 2) + "\n");
fs.writeFileSync(
  jsPath,
  "// AUTO-GENERATED by scripts/extract-focus-costs.js from items.xml — do not edit by hand.\n" +
  "// Per-item base crafting focus cost (0 spec). Re-run after an items.xml refresh.\n" +
  "const FOCUS_COSTS = " + JSON.stringify(sorted) + ";\n" +
  "if (typeof module !== \"undefined\" && module.exports) { module.exports = { FOCUS_COSTS }; }\n"
);

console.log(`Extracted ${Object.keys(sorted).length} focus costs → ${jsPath} + ${jsonPath}`);

// Print some verification samples
const samples = [
  "T8_FURNITUREITEM_REPAIRKIT",
  "T8_METALBAR",
  "T4_METALBAR",
  "T4_METALBAR_LEVEL1@1",
  "T4_POTION_HEAL",
  "T4_MAIN_SWORD",
  "T8_MOUNT_RABBIT_EASTER_DARK",
  "T4_2H_SHAPESHIFTER_SET1",
];
for (const s of samples) {
  console.log(`  ${s}: ${sorted[s] || "NOT FOUND"}`);
}
