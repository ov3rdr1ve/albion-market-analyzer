/**
 * Extract per-item weight + fasttravelfactor from items.xml → js/data-weights.js
 *
 * Scope: the finished-good families where the tier weight formula isn't
 * accurate — Brecilien travel cost, and the Flipping table's Ox Load column —
 *   - Capes  (uniquename contains CAPE, which also covers the CAPEITEM_*_BP crests)
 *   - Bags   (uniquename contains _BAG)
 *   - Potions(uniquename contains _POTION_)
 *   - Meals / food (uniquename contains _MEAL_)
 *   - Farming outputs (resourcetype CROP / HERB / PRODUCTS — crops, herbs, eggs, milk)
 *   - Artifacts (ARTEFACT), alchemy remains + extracts (ALCHEMY), essence,
 *     mount upgrade kits, faction tokens (QUESTITEM_TOKEN) and dungeon maps.
 *     These are small, hand-carried items; without a real weight they fall
 *     through to the finished-good estimate in js/travel-cost.js, which would
 *     put a T7 animal remain at ~30 kg.
 *
 * Raw + refined RESOURCES are intentionally excluded: their weight follows
 * 0.1*1.5^tier exactly (matches items.xml) and their fasttravelfactor doubles
 * with both tier and enchant level — min(256, 2^(tier-3+enchant)), e.g. T4.0=2,
 * T4.1=4, T5.0=4 — both handled by js/travel-cost.js without a table.
 *
 * Output globals (mirrors js/focus-costs.js single-line generated style):
 *   const ITEM_WEIGHTS    = { "<id>": <kg>, ... }      // base ids, no enchant suffix
 *   const ITEM_FT_FACTORS = { "<id>": <factor>, ... }  // only entries != 1
 *
 * Usage: node scripts/extract-weights.js
 */
const fs = require("fs");
const path = require("path");

const xmlPath = path.join(__dirname, "..", "data", "dumps", "items.xml");
const outPath = path.join(__dirname, "..", "js", "data-weights.js");

const xml = fs.readFileSync(xmlPath, "utf-8");
const lines = xml.split("\n");

// Element types that can carry a tradeable weight we care about.
const ITEM_TAG_RE =
  /<(?:simpleitem|consumableitem|consumablefrominventoryitem|equipmentitem|weaponitem|farmableitem|furnitureitem)\s[^>]*?uniquename="([^"]+)"[^>]*>/;

// Family membership by id (capes, bags, potions, meals, artifacts, alchemy,
// essence, mount upgrades, tokens, maps) + farming outputs by resourcetype.
function isWantedFamily(uniquename, line) {
  if (/CAPE/.test(uniquename)) return true;
  if (/_BAG\b/.test(uniquename) || /_BAG_/.test(uniquename) || /_BAG$/.test(uniquename)) return true;
  if (/_POTION_/.test(uniquename)) return true;
  if (/_MEAL_/.test(uniquename)) return true;
  if (/ARTEFACT/.test(uniquename)) return true;
  if (/ALCHEMY/.test(uniquename)) return true;
  if (/_ESSENCE(_|$)/.test(uniquename)) return true;
  if (/MOUNTUPGRADE/.test(uniquename)) return true;
  if (/^QUESTITEM_TOKEN_/.test(uniquename)) return true;
  if (/_MAP$/.test(uniquename) || /RANDOM_DUNGEON/.test(uniquename)) return true;
  const rt = line.match(/resourcetype="([^"]+)"/);
  if (rt && /^(CROP|HERB|PRODUCTS)$/.test(rt[1])) return true;
  return false;
}

// Normalise to base id (drop enchant decorations) so the runtime lookup, which
// also strips @N / _LEVELN, hits these keys. Skip pure-enchant duplicate rows.
function baseId(uniquename) {
  return uniquename.replace(/@\d+$/, "").replace(/_LEVEL\d+$/, "");
}

const weights = {};
const factors = {};

for (const line of lines) {
  const m = line.match(ITEM_TAG_RE);
  if (!m) continue;
  const uniquename = m[1];
  if (!isWantedFamily(uniquename, line)) continue;

  const wMatch = line.match(/\sweight="([0-9.]+)"/);
  if (!wMatch) continue; // no weight → nothing to record
  const weight = parseFloat(wMatch[1]);
  if (!(weight > 0)) continue;

  const id = baseId(uniquename);
  if (!(id in weights)) weights[id] = weight; // first (base) wins

  const fMatch = line.match(/fasttravelfactor="([0-9.]+)"/);
  if (fMatch) {
    const f = parseFloat(fMatch[1]);
    if (f !== 1 && !(id in factors)) factors[id] = f;
  }
}

const sortObj = (o) =>
  Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));

const sortedWeights = sortObj(weights);
const sortedFactors = sortObj(factors);

const banner =
  "// AUTO-GENERATED by scripts/extract-weights.js — do not edit by hand.\n" +
  "// Per-item travel weight (kg) + fasttravelfactor for Brecilien Travel Planner\n" +
  "// cost and the Flipping table Ox Load column. Scope: capes, bags, potions,\n" +
  "// meals, farming outputs, artifacts, alchemy, essence, mount upgrades,\n" +
  "// tokens and dungeon maps. Resources are\n" +
  "// handled by formula in js/travel-cost.js and intentionally absent here.\n";

const body =
  banner +
  "const ITEM_WEIGHTS = " + JSON.stringify(sortedWeights) + ";\n" +
  "const ITEM_FT_FACTORS = " + JSON.stringify(sortedFactors) + ";\n" +
  "if (typeof module !== \"undefined\" && module.exports) {\n" +
  "  module.exports = { ITEM_WEIGHTS, ITEM_FT_FACTORS };\n" +
  "}\n";

fs.writeFileSync(outPath, body);

console.log(
  `Extracted ${Object.keys(sortedWeights).length} weights, ` +
  `${Object.keys(sortedFactors).length} non-default factors → ${outPath}`,
);

// Verification samples
const samples = [
  "T5_MEAL_SOUP", "T4_POTION_HEAL", "T1_CARROT", "T4_TURNIP", "T8_PUMPKIN",
  "T3_EGG", "T4_MILK", "T2_AGARIC",
];
for (const s of samples) {
  console.log(`  ${s}: weight=${sortedWeights[s] ?? "—"} factor=${sortedFactors[s] ?? 1}`);
}
// Show a few cape/bag ids that were captured (id format varies).
const capeIds = Object.keys(sortedWeights).filter((k) => /CAPE/.test(k)).slice(0, 4);
const bagIds = Object.keys(sortedWeights).filter((k) => /_BAG/.test(k)).slice(0, 4);
console.log("  sample capes:", capeIds.length ? capeIds.join(", ") : "(none)");
console.log("  sample bags: ", bagIds.length ? bagIds.join(", ") : "(none)");
