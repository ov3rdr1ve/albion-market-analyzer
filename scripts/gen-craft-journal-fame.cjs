/**
 * Generate js/data-craft-journal-fame.js from items.xml.
 *
 * Which crafting journal a craft fills was a hand-written craftType → slug table
 * (CRAFT_JOURNAL_BY_TYPE in js/data-craft-planner.js). It was a guess, and it
 * was wrong in both directions: capes, bags, gatherer gear and the Avalonian
 * tools fill the Toolmaker journal and showed nothing, while the artifact and
 * faction capes (Avalonian / Brecilien / Smuggler) fill NO journal at all and a
 * craftType rule would have wrongly credited them.
 *
 * items.xml answers it exactly. Every journal carries the list:
 *
 *   <journalitem uniquename="T8_JOURNAL_TOOLMAKER" maxfame="58590" …>
 *     <famefillingmissions>
 *       <craftitemfame mintier="8" value="19200">
 *         <validitem id="T8_CAPE" />
 *         <validitem id="T8_BAG" />
 *         …
 *
 * Two facts fall out of that block, both of which the old table got wrong:
 *   • the valid items are ALL of the journal's own tier — a T8 craft cannot fill
 *     a T6 crafting journal, so the ±2 window the gathering journals use does
 *     not apply here;
 *   • `maxfame` is per journal tier and the T7/T8 numbers are not the round
 *     doubling the hand-written table assumed (28380 / 58590, not 28800/57600).
 *
 * Run: node scripts/gen-craft-journal-fame.cjs
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const SRC = path.join(ROOT, "data", "dumps", "items.xml");
const OUT = path.join(ROOT, "js", "data-craft-journal-fame.js");

// The four crafting-profession journals. The gathering / trophy / mercenary
// journals fill from activity fame, not from a list of crafted items, and are
// modelled separately in js/data-journals.js.
const CRAFT_SLUGS = ["WARRIOR", "HUNTER", "MAGE", "TOOLMAKER"];

const xml = fs.readFileSync(SRC, "utf8");

const JOURNAL_RE =
  /<journalitem[^>]*uniquename="T(\d)_JOURNAL_([A-Z]+)"[^>]*maxfame="(\d+)"[\s\S]*?<\/journalitem>/g;

const maxfameByTier = {}; // tier → maxfame (identical across the four slugs)
const famePerCraftByTier = {}; // tier → craftitemfame `value`
const itemToSlug = {}; // exact item id (tier included, no @n) → slug
let items = 0;
let journals = 0;

let m;
while ((m = JOURNAL_RE.exec(xml))) {
  const tier = Number(m[1]);
  const slug = m[2];
  if (!CRAFT_SLUGS.includes(slug)) continue;
  const block = m[0].match(/<craftitemfame([^>]*)>([\s\S]*?)<\/craftitemfame>/);
  if (!block) continue;
  journals++;
  maxfameByTier[tier] = Number(m[3]);
  const value = Number((block[1].match(/value="(\d+)"/) || [])[1]) || 0;
  if (value) famePerCraftByTier[tier] = value;
  [...block[2].matchAll(/id="([^"]+)"/g)].forEach((v) => {
    const id = v[1];
    // First writer wins; the lists are disjoint across slugs in practice, and a
    // duplicate would mean the item fills either journal — keeping one is fine.
    if (!itemToSlug[id]) {
      itemToSlug[id] = slug;
      items++;
    }
  });
}

const tiers = Object.keys(maxfameByTier)
  .map(Number)
  .sort((a, b) => a - b);

const body = `// AUTO-GENERATED by scripts/gen-craft-journal-fame.cjs from items.xml — do not edit by hand.
// Which crafting journal each craftable item fills, straight from every
// <journalitem>'s <craftitemfame><validitem> list. An item that appears in no
// list fills no crafting journal — the artifact and faction capes, the artifact
// off-hands and every consumable/mount are genuinely absent, and must show no
// journal value rather than one inferred from their craft type.
// Re-run after an items.xml refresh.

// Journal tier → fame that fills it (items.xml \`maxfame\`).
const CRAFT_JOURNAL_MAXFAME = ${JSON.stringify(
  Object.fromEntries(tiers.map((t) => [t, maxfameByTier[t]])),
)};

// Journal tier → the \`value\` items.xml puts on the craftitemfame block. Not the
// fill requirement (that is maxfame); kept because it is the only per-tier
// figure the game files attach to a craft, and the tests assert it stays in
// step with maxfame.
const CRAFT_JOURNAL_CRAFTITEM_VALUE = ${JSON.stringify(
  Object.fromEntries(tiers.map((t) => [t, famePerCraftByTier[t] || 0])),
)};

// Exact item id (tier included, no @n enchant suffix) → journal slug.
const CRAFT_JOURNAL_BY_ITEM = ${JSON.stringify(itemToSlug)};

// Strip only the enchant suffix: the tier is part of the key, because a journal
// is filled solely by crafts of its OWN tier.
function craftJournalItemKey(id) {
  return String(id || "").replace(/@\\d+$/, "");
}

/**
 * The crafting journal one craft fills.
 * @returns {{slug: string, tier: number, maxfame: number}|null} null when the
 *   item fills no crafting journal.
 */
function getCraftJournalForItem(id) {
  const key = craftJournalItemKey(id);
  const slug = CRAFT_JOURNAL_BY_ITEM[key];
  if (!slug) return null;
  const m = key.match(/^T(\\d)_/);
  const tier = m ? Number(m[1]) : 0;
  const maxfame = CRAFT_JOURNAL_MAXFAME[tier] || 0;
  if (!maxfame) return null;
  return { slug, tier, maxfame };
}

if (typeof module !== "undefined" && module.exports) {
  module.exports = {
    CRAFT_JOURNAL_MAXFAME,
    CRAFT_JOURNAL_CRAFTITEM_VALUE,
    CRAFT_JOURNAL_BY_ITEM,
    craftJournalItemKey,
    getCraftJournalForItem,
  };
  if (typeof globalThis !== "undefined") {
    globalThis.CRAFT_JOURNAL_MAXFAME = CRAFT_JOURNAL_MAXFAME;
    globalThis.CRAFT_JOURNAL_CRAFTITEM_VALUE = CRAFT_JOURNAL_CRAFTITEM_VALUE;
    globalThis.CRAFT_JOURNAL_BY_ITEM = CRAFT_JOURNAL_BY_ITEM;
    globalThis.craftJournalItemKey = craftJournalItemKey;
    globalThis.getCraftJournalForItem = getCraftJournalForItem;
  }
}
`;

fs.writeFileSync(OUT, body, "utf8");
console.log(
  `wrote ${path.relative(ROOT, OUT)}: ${items} items across ${journals} journals, ` +
    `tiers ${tiers.join("/")}`,
);
