/**
 * Generates js/item-values.js — the items.xml "item value" of every T4-T8
 * equipment piece.
 *
 * Item value is what the game bills station fees, repair and quality rerolls
 * against. Equipment carries no `itemvalue` attribute of its own: it is the sum
 * of its crafting materials' item values, doubling per enchantment level of the
 * material. Materials that are themselves crafted (a faction cape is built on a
 * plain cape) resolve recursively.
 *
 * Cross-check: the wiki's reroll-cost example uses item value 512, which is
 * exactly a T4 two-handed weapon (32 x T4_METALBAR @ 16).
 *
 * Run: node scripts/gen-item-values.cjs
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const xml = fs.readFileSync(path.join(ROOT, "data", "dumps", "items.xml"), "utf8");

// ─── Declared item values (simple items, artifacts, resources) ───────────────
const declared = {};
for (const m of xml.matchAll(/uniquename="([^"]+)"([^>]*?)itemvalue="([0-9.]+)"/g)) {
  declared[m[1]] = parseFloat(m[3]);
}

// ─── Crafting recipes, so crafted items can be valued from their materials ───
const ITEM_TAGS = [
  "weapon",
  "equipmentitem",
  "simpleitem",
  "consumableitem",
  "furnitureitem",
  "mount",
  "journalitem",
  "trackingitem",
].join("|");

const recipes = {};
const tagRe = new RegExp(`<(${ITEM_TAGS})\\s+uniquename="([^"]+)"`, "g");
let m;
while ((m = tagRe.exec(xml))) {
  const [tag, id] = [m[1], m[2]];
  if (recipes[id]) continue;
  const openEnd = xml.indexOf(">", m.index);
  if (openEnd < 0 || xml[openEnd - 1] === "/") continue; // self-closing: no recipe
  const close = xml.indexOf(`</${tag}>`, openEnd);
  if (close < 0) continue;
  const body = xml.slice(openEnd, close);
  const start = body.indexOf("<craftingrequirements");
  if (start < 0) continue;
  const end = body.indexOf("</craftingrequirements>", start);
  const block = end < 0 ? body.slice(start, body.indexOf(">", start)) : body.slice(start, end);
  const mats = [];
  for (const r of block.matchAll(/<craftresource uniquename="([^"]+)" count="(\d+)"([^>]*)/g)) {
    const ench = /enchantmentlevel="(\d+)"/.exec(r[3]);
    mats.push({ id: r[1], count: Number(r[2]), ench: ench ? Number(ench[1]) : 0 });
  }
  if (mats.length) recipes[id] = mats;
}

// ─── Resolve ─────────────────────────────────────────────────────────────────
const cache = {};
function itemValue(id, depth = 0) {
  if (declared[id] != null) return declared[id];
  if (cache[id] != null) return cache[id];
  if (depth > 6) return 0;
  const mats = recipes[id];
  if (!mats) return 0;
  cache[id] = 0; // cycle guard
  const total = mats.reduce(
    (sum, mat) => sum + mat.count * itemValue(mat.id, depth + 1) * Math.pow(2, mat.ench),
    0,
  );
  cache[id] = total;
  return total;
}

const values = {};
const eqRe = /<(weapon|equipmentitem|mount)\s+uniquename="(T[4-8]_[^"@]+)"/g;
let e;
while ((e = eqRe.exec(xml))) {
  const id = e[2];
  if (values[id] != null) continue;
  if (id.includes("_DEBUG_")) continue;
  const v = itemValue(id);
  if (v > 0) values[id] = v;
}

const sorted = {};
Object.keys(values)
  .sort()
  .forEach((k) => (sorted[k] = values[k]));

const out = `// AUTO-GENERATED by scripts/gen-item-values.cjs from items.xml — do not edit by hand.
// items.xml item value of each T4-T8 equipment piece (sum of its crafting
// materials' item values). Drives quality-reroll pricing. Re-run after an
// items.xml refresh.
const ITEM_VALUES = ${JSON.stringify(sorted)};
`;

fs.writeFileSync(path.join(ROOT, "js", "item-values.js"), out);
console.log(`Wrote js/item-values.js — ${Object.keys(sorted).length} equipment item values.`);
