// Generates js/consumable-output.js (+ .json) from items.xml.
//
// Maps each cooked MEAL / brewed POTION recipe id to its `amountcrafted` — the
// number of units one craft action yields (salads/most potions = 10, heal
// potions = 5, single-ingredient foods = 1). The consumables craft branch needs
// this to price materials PER OUTPUT UNIT instead of per batch; without it,
// batch-yield meals show a ~10×/5× false loss. Enchant variants (id@n) reuse the
// base recipe, so only base ids are emitted — getRecipeOutput strips the suffix.
//
// Run after an items.xml refresh:  node scripts/extract-consumable-output.cjs

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const xml = fs.readFileSync(path.join(ROOT, "data", "dumps", "items.xml"), "utf-8");

const ids = [
  ...new Set(
    [...xml.matchAll(/uniquename="(T[0-9]_(?:MEAL|POTION)_[A-Z0-9_]*)"/g)].map((m) => m[1])
  ),
];

const out = {};
for (const id of ids) {
  // Anchor on the item's DEFINITION element. Definition tags end in "item"
  // (consumableitem, simpleitem, …); a <craftresource> reference to this id in
  // another recipe never does — so this can't read a neighbour's batch size.
  // Read amountcrafted ONLY from the first <craftingrequirements> opening tag
  // (it precedes any nested <craftresource>), so a missing attribute defaults to
  // 1 instead of bleeding into the next element. (ids are [A-Z0-9_], no meta.)
  const m = xml.match(new RegExp(`<[a-z]+item[^>]*\\buniquename="${id}"[^>]*>([\\s\\S]{0,300})`));
  if (!m) continue;
  const crTag = m[1].match(/<craftingrequirements[^>]*>/);
  if (!crTag) continue; // not craftable
  const a = crTag[0].match(/amountcrafted="(\d+)"/);
  out[id] = a ? parseInt(a[1], 10) : 1;
}

// Stable, deterministic ordering for clean diffs.
const sorted = {};
for (const k of Object.keys(out).sort()) sorted[k] = out[k];

const counts = Object.values(sorted).reduce((a, n) => ((a[n] = (a[n] || 0) + 1), a), {});

fs.writeFileSync(
  path.join(ROOT, "js", "consumable-output.json"),
  JSON.stringify(sorted, null, 0) + "\n"
);
fs.writeFileSync(
  path.join(ROOT, "js", "consumable-output.js"),
  "// AUTO-GENERATED by scripts/extract-consumable-output.cjs from items.xml — do not edit by hand.\n" +
    "// Per-recipe craft yield (amountcrafted): units produced per craft action.\n" +
    "// Used by getRecipeOutput() to price consumable materials per output unit.\n" +
    "const CONSUMABLE_OUTPUT = " + JSON.stringify(sorted) + ";\n" +
    "if (typeof module !== \"undefined\" && module.exports) module.exports = CONSUMABLE_OUTPUT;\n"
);

console.log(`Wrote ${Object.keys(sorted).length} consumable outputs.`);
console.log("amountcrafted distribution:", counts);
